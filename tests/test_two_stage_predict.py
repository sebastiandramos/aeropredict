"""Tests for the two-stage delay model (notebook R port) and its API wiring.

The artifact lives in ``models/`` and is generated by
``scripts/export_r_model_to_python.py``. Tests skip when it is absent (fresh
checkout without a build step).
"""

from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from src.aeropredict.api.predict import (
    DEFAULT_ARTIFACT_PATH,
    DEFAULT_RULES_PATH,
    TwoStageDelayModel,
    map_payload_to_model_features,
)
from src.aeropredict.api.server import app

ARTIFACT_PATH = Path(DEFAULT_ARTIFACT_PATH)
RULES_PATH = Path(DEFAULT_RULES_PATH)

pytestmark = pytest.mark.skipif(
    not (ARTIFACT_PATH.exists() and RULES_PATH.exists()),
    reason="two-stage artifact not generated; run scripts/export_r_model_to_python.py",
)

BASE_PAYLOAD = {
    "hour_of_day": 14,
    "day_of_week": 2,
    "airline": "IB",
    "route_distance": 500.0,
    "origin_iata": "LEMD",
    "destination_iata": "LEBL",
    "weather_temperature_2m": 20.0,
    "dew_point_c": 10.0,
    "relative_humidity": 55.0,
}


@pytest.fixture(scope="module")
def model() -> TwoStageDelayModel:
    return TwoStageDelayModel.load()


def test_artifact_metadata(model: TwoStageDelayModel) -> None:
    assert model.version == "1.0.0"
    assert 0.0 < model.threshold < 0.5
    assert len(model.columns_classification_design) == len(
        model.coefficients_classification
    )
    assert set(model.imputation) == {
        "temperatura_metar",
        "punto_rocio_metar",
        "relh",
    }


def test_predict_returns_full_contract(model: TwoStageDelayModel) -> None:
    result = model.predict(dict(BASE_PAYLOAD))

    probability = result["prob_retraso"]
    assert 0.0 <= probability <= 1.0
    assert isinstance(result["prediccion_retraso_15min"], bool)
    assert result["prediccion_retraso_15min"] == (probability >= model.threshold)
    assert result["umbral_aplicado"] == model.threshold
    assert result["model_version"] == f"two-stage-{model.version}"

    if result["prediccion_retraso_15min"]:
        assert result["minutos_retraso_estimados"] >= 15.0
    else:
        assert result["minutos_retraso_estimados"] == 0.0

    assert result["factores"], "expected model explanations"
    for factor in result["factores"]:
        assert factor["impact"] in {"positive", "negative"}
        assert factor["title"]
        assert factor["description"]


def test_missing_weather_is_imputed(model: TwoStageDelayModel) -> None:
    payload = {
        key: value
        for key, value in BASE_PAYLOAD.items()
        if key not in {"dew_point_c", "relative_humidity"}
    }
    features, imputed, _ = map_payload_to_model_features(
        payload, imputation=model.imputation
    )
    assert "punto_rocio_metar" in imputed
    assert model.imputation["punto_rocio_metar"] == features["punto_rocio_metar"]

    result = model.predict(payload)
    assert "punto_rocio_metar" in result["imputaciones"]


def test_weather_derivations() -> None:
    # dew point derivable from temperature + humidity
    features, imputed, _ = map_payload_to_model_features(
        {
            "hour_of_day": 10,
            "day_of_week": 1,
            "airline": "IB",
            "origin_iata": "LEMD",
            "destination_iata": "LEBL",
            "weather_temperature_2m": 25.0,
            "relative_humidity": 60.0,
        },
        imputation={"temperatura_metar": 27.0, "punto_rocio_metar": 11.0, "relh": 41.0},
    )
    assert "punto_rocio_metar" not in imputed
    assert 10.0 < features["punto_rocio_metar"] < 20.0

    # humidity derivable from temperature + dew point
    features, imputed, _ = map_payload_to_model_features(
        {
            "hour_of_day": 10,
            "day_of_week": 1,
            "airline": "IB",
            "origin_iata": "LEMD",
            "destination_iata": "LEBL",
            "weather_temperature_2m": 25.0,
            "dew_point_c": 15.0,
        },
        imputation={"temperatura_metar": 27.0, "punto_rocio_metar": 11.0, "relh": 41.0},
    )
    assert "relh" not in imputed
    assert 40.0 < features["relh"] < 60.0


def test_other_airport_selection() -> None:
    imputation = {"temperatura_metar": 27.0, "punto_rocio_metar": 11.0, "relh": 41.0}

    # AENA origin + foreign destination -> destination is the "other" airport
    _, _, resolved = map_payload_to_model_features(
        {**BASE_PAYLOAD, "origin_iata": "LEMD", "destination_iata": "LPPT"},
        imputation=imputation,
    )
    assert resolved["other_airport_iata"] == "LIS"

    # Foreign origin + AENA destination -> origin is the "other" airport
    _, _, resolved = map_payload_to_model_features(
        {**BASE_PAYLOAD, "origin_iata": "LPPT", "destination_iata": "LEBL"},
        imputation=imputation,
    )
    assert resolved["other_airport_iata"] == "LIS"

    # Explicit IATA override wins
    _, _, resolved = map_payload_to_model_features(
        {**BASE_PAYLOAD, "other_airport_iata": "EGLL"},
        imputation=imputation,
    )
    assert resolved["other_airport_iata"] == "EGLL"


def test_http_delay_endpoint_uses_two_stage(monkeypatch: pytest.MonkeyPatch) -> None:
    client = TestClient(app)
    previous = (
        getattr(app.state, "two_stage_model", None),
        getattr(app.state, "model", None),
        getattr(app.state, "model_version", None),
        getattr(app.state, "model_source", None),
    )
    app.state.two_stage_model = TwoStageDelayModel.load()
    app.state.model = None
    app.state.model_version = "two-stage-1.0.0"
    app.state.model_source = "local_artifact"
    try:
        response = client.post("/predict/delay", json=BASE_PAYLOAD)
    finally:
        (
            app.state.two_stage_model,
            app.state.model,
            app.state.model_version,
            app.state.model_source,
        ) = previous

    assert response.status_code == 200
    data = response.json()
    assert 0.0 <= data["prob_retraso"] <= 1.0
    assert data["model_source"] == "local_artifact"
    assert data["model_version"].startswith("two-stage-")
    assert data["factores"]
    assert data["predicted_delay_minutes"] == data["minutos_retraso_estimados"]
    assert data["confidence"] == pytest.approx(
        data["prob_retraso"]
        if data["prediccion_retraso_15min"]
        else 1.0 - data["prob_retraso"]
    )


